"""Saved lyric appearances and live timing through the React controls."""
from playwright.sync_api import expect
from browser_cases import YOUTUBE_FIXTURE, LyricsOutput


def exercise_song_settings(page):
    songs = [{'title': title, 'url': 'https://www.youtube.com/watch?v=dz3sM6ygX_g',
              'lrc': '[00:00]First line\n[00:05]Second line', 'off': 0, 'pitch': 0,
              'libraryId': identity, 'librarySync': True}
             for title, identity in [('Style A', 'style-a'), ('Style B', 'style-b')]]
    page.route('https://www.youtube.com/iframe_api', lambda route: route.fulfill(content_type='application/javascript', body=YOUTUBE_FIXTURE))
    page.evaluate('(songs)=>{localStorage.kpt2=JSON.stringify(songs);localStorage.kpt_set=JSON.stringify({fxv:1,cdn:0,lfx:"clean"})}', songs)
    page.reload()
    page.wait_for_function('() => document.querySelector("#relayStatus").dataset.state==="connected"')
    page.locator('#list [data-a="go"]').first.click()
    page.wait_for_function('() => window.testYT?.getPlayerState()===1')
    page.locator('#pause').click()
    page.evaluate('testYT.seekTo(4.8)')
    output_page = page.context.new_page()
    try:
        output_page.goto(page.locator('#obsurl').input_value())
        output = LyricsOutput(output_page)
        output.wait_for_function('() => window.ManokaraOutput?.getSnapshot()?.paused')
        before = output.evaluate('ManokaraOutput.time()')
        page.locator('#lp').click()
        output.wait_for_function('(before)=>ManokaraOutput.time()>before+.4', arg=before)
        expect(page.locator('#pan .cl')).to_have_text('Second line')
        page.wait_for_function('() => new Promise(resolve=>{const open=indexedDB.open("manokara-library",1);open.onsuccess=()=>{const db=open.result,r=db.transaction("songs").objectStore("songs").get("style-a");r.onsuccess=()=>{db.close();resolve(r.result?.off===.5)}}})')
        page.locator('#rememberSongStyle').check()
        page.locator('#lfx').select_option('karaoke-classic')
        page.locator('#lclassiccolor').evaluate('(el)=>{Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,"value").set.call(el,"#fb7185");el.dispatchEvent(new Event("input",{bubbles:true}));el.dispatchEvent(new Event("change",{bubbles:true}))}')
        page.wait_for_function('() => JSON.parse(localStorage.kpt2)[0].lyricStyle.lclassiccolor==="#fb7185"')
        output.wait_for_function('() => ManokaraOutput.getSnapshot().effect==="karaoke-classic" && ManokaraOutput.getSnapshot().foreground==="#fb7185"')
        assert page.evaluate('JSON.parse(localStorage.kpt_set).lfx') == 'clean'
        page.locator('#list [data-a="go"]').nth(1).click()
        expect(page.locator('#lfx')).to_have_value('clean')
        expect(page.locator('#rememberSongStyle')).not_to_be_checked()
        page.locator('#rememberSongStyle').check()
        page.locator('#lfx').select_option('jizura')
        page.locator('#lrandom').click()
        seed = page.evaluate('JSON.parse(localStorage.kpt2)[1].lyricStyle.themeSeed')
        page.locator('#list [data-a="go"]').first.click()
        expect(page.locator('#lfx')).to_have_value('karaoke-classic')
        expect(page.locator('#lclassiccolor')).to_have_value('#fb7185')
        expect(page.locator('#offv')).to_contain_text('0.5')
        page.locator('#list [data-a="go"]').nth(1).click()
        output.wait_for_function('(seed)=>ManokaraOutput.getSnapshot().effect==="jizura" && ManokaraOutput.getSnapshot().themeSeed===seed', arg=seed)
        page.locator('#list [data-a="go"]').first.click()
        page.locator('#list [data-a="ed"]').first.click()
        page.locator('#songEditorDialog #ttl').fill('Style A edited')
        page.locator('#songEditorDialog #add').click()
        page.locator('#songEditorDialog').wait_for(state='hidden')
        assert page.evaluate('JSON.parse(localStorage.kpt2)[0].lyricStyle.lfx') == 'karaoke-classic'
        page.reload()
        page.wait_for_function('() => document.querySelector("#relayStatus").dataset.state==="connected"')
        page.locator('#list [data-a="go"]').first.click()
        expect(page.locator('#rememberSongStyle')).to_be_checked()
        expect(page.locator('#lfx')).to_have_value('karaoke-classic')
        page.locator('#lz').click()
        page.wait_for_function('() => JSON.parse(localStorage.kpt2)[0].off===0')
        page.locator('#rememberSongStyle').uncheck()
        expect(page.locator('#lfx')).to_have_value('clean')
        assert page.evaluate('!JSON.parse(localStorage.kpt2)[0].lyricStyle')
        page.locator('#rememberSongStyle').check()
        page.locator('#lfx').select_option('word-pop')
        page.wait_for_function('() => new Promise(resolve=>{const open=indexedDB.open("manokara-library",1);open.onsuccess=()=>{const db=open.result,r=db.transaction("songs").objectStore("songs").get("style-a");r.onsuccess=()=>{db.close();resolve(r.result?.lyricStyle?.lfx==="word-pop" && r.result.off===0)}}})')
        page.locator('#stop').click()
        expect(page.locator('#lfx')).to_have_value('clean')
        page.once('dialog', lambda dialog: dialog.accept())
        page.get_by_role('button', name='Clear setlist', exact=True).click()
        page.get_by_role('button', name='My songs', exact=False).click()
        row = page.locator('#libraryList li').filter(has_text='Style A edited')
        row.get_by_role('button', name='Add', exact=True).click()
        page.locator('#list [data-a="go"]').first.click()
        expect(page.locator('#lfx')).to_have_value('word-pop')
        expect(page.locator('#rememberSongStyle')).to_be_checked()
        print('Song settings passed: live offset reaches OBS and lyrics immediately, library offset persists, per-song effect/color/JIZURA seed restores, shared defaults stay separate, editor/reload preserve settings, clearing/re-adding from library keeps style.')
    finally:
        output_page.close()
        page.unroute('https://www.youtube.com/iframe_api')
